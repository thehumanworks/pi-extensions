import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

function rng(seed) {
	return () => {
		seed = (seed * 1103515245 + 12345) % 2147483648;
		return seed / 2147483648;
	};
}

function design() {
	const sections = [
		["Purpose", "The tasks service stores to-do items for small teams and exposes them over a JSON HTTP API. It runs as a single Node process with an in-memory store that is snapshotted to disk."],
		["Resources", "A task has `id`, `title`, `status` (`open` or `done`), `created_at`, `updated_at`, and `deleted_at`. IDs are ULIDs generated by the server. Clients never choose IDs."],
		["Timestamps", "Every timestamp is RFC 3339 in UTC. Responses and stored values must be byte-identical across reads, so serialization must not change precision between write and read."],
		["Pagination", "List endpoints use cursor pagination. The `cursor` query parameter is an opaque string returned as `next_cursor`; offsets are not supported. `limit` defaults to 25 and may not exceed 100. Invalid limits are a 400 error, not silently clamped."],
		["Errors", "Every error response uses the envelope `{\"error\": {\"code\": \"...\", \"message\": \"...\"}}` with a stable, snake_case `code` such as `invalid_limit` or `not_found`. Messages are for humans and may change."],
		["Deletion", "Deletes are soft: the server sets `deleted_at` and the task disappears from listings and GETs, which return 404. A deleted task can be restored within 30 days."],
		["Rate limits", "Each API token may make 120 requests per minute. Excess requests receive 429 with the error envelope and a `Retry-After` header in whole seconds."],
		["Observability", "Logs are structured JSON lines. Request bodies are never logged."],
	];
	const next = rng(11);
	let text = "# tasks service design\n\n";
	for (const [title, body] of sections) {
		text += `## ${title}\n\n${body}\n\n`;
		for (let i = 0; i < 6; i++) {
			text += `Discussion ${title.toLowerCase()}-${i + 1}: this paragraph records background for reviewers on item ${Math.floor(next() * 900 + 100)}; it restates the context above for readers who jump straight to this section and adds no requirement of its own.\n\n`;
		}
	}
	return text;
}

